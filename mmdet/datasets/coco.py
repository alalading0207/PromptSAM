    def load_data_list(self) -> List[dict]:
        """Load annotations from an annotation file named as ``self.ann_file``

        Returns:
            List[dict]: A list of annotation.
        """  # noqa: E501
        with get_local_path(
                self.ann_file, backend_args=self.backend_args) as local_path:  # 获取了json路径
            self.coco = self.COCOAPI(local_path)   # 读取json文件   获取 anns、imgs、cats、imgToAnns=img_ann_map、catToImgs=cat_img_map、
